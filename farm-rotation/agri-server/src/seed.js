function seedIfEmpty(db) {
  const count = db.prepare('SELECT COUNT(*) AS n FROM fields').get().n;
  if (count > 0) return false;

  const cropMap = Object.fromEntries(CROPS.map(c => [c[0], c[1]]));

  const insertField = db.prepare(
    'INSERT INTO fields (code, name, area_mu, soil_type) VALUES (?, ?, ?, ?)'
  );
  const insertCrop = db.prepare(
    'INSERT INTO crops (name, family, sow_months, duration_months, note) VALUES (?, ?, ?, ?, ?)'
  );
  const insertRecord = db.prepare(`
    INSERT INTO crop_records
      (field_id, crop_name, variety, family, sow_date, fertilizer_type, fertilizer_amount, irrigate_date, harvest_yield)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
  `);

  db.transaction(() => {
    for (const c of CROPS) insertCrop.run(...c);

    const fieldIds = {};
    for (const f of FIELDS) {
      fieldIds[f[0]] = insertField.run(...f).lastInsertRowid;
    }

    for (const r of RECORDS) {
      const [code, crop, variety, sow, fertType, fertAmt, irrigate, yield_] = r;
      insertRecord.run(
        fieldIds[code], crop, variety, cropMap[crop] || '其他',
        sow, fertType, fertAmt, irrigate, yield_
      );
    }
  })();

  console.log(`[seed] 已写入 ${FIELDS.length} 块地、${CROPS.length} 种作物、${RECORDS.length} 条茬口记录`);
  return true;
}

